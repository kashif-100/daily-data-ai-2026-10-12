"""Movie Recommender — collaborative filtering on synthetic ratings.

Pipeline:
1. Loads the synthetic ratings (generated by generate_data.py).
2. Holds out 3 ratings per heavy user to create a train/test split.
3. Builds an ITEM-ITEM cosine-similarity model (the "people who liked X also
   liked Y" engine) and two baselines: USER-USER similarity and raw popularity.
4. Evaluates all three with RMSE/MAE on held-out ratings and Precision@5 /
   Recall@5 on top-5 recommendation lists.
5. Generates explained top-5 recommendations for a demo user.
6. Saves 4 charts + findings.json (input for ai_insights.py).

No external APIs, no real user data — everything is synthetic (seed 42).
"""
import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from sklearn.metrics.pairwise import cosine_similarity

sns.set_theme(style="whitegrid")
rng = np.random.default_rng(42)

K_ITEM = 15   # neighbours for item-item predictions
K_USER = 25   # neighbours for user-user predictions
TOP_N = 5

movies = pd.read_csv("data/movies.csv")
ratings = pd.read_csv("data/ratings.csv")
print(f"{len(ratings):,} ratings | {ratings.user_id.nunique()} users | "
      f"{len(movies)} movies | density {len(ratings) / (300 * 120):.1%}")

# ----------------------- train / test split (holdout) ------------------------
# Users with >= 12 ratings give up 3 ratings as a test set; everything else trains.
test_pairs = []   # (user_id, movie_id, true_rating)
train_ratings = ratings.copy()
counts = ratings["user_id"].value_counts()
heavy = counts[counts >= 12].index
drop_idx = []
for u in heavy:
    idx = ratings.index[ratings.user_id == u].to_numpy()
    chosen = rng.choice(idx, size=3, replace=False)
    drop_idx.extend(chosen)
    for i in chosen:
        r = ratings.loc[i]
        test_pairs.append((r["user_id"], r["movie_id"], r["rating"]))
train_ratings = ratings.drop(index=drop_idx).reset_index(drop=True)
print(f"Train: {len(train_ratings):,} ratings | Test: {len(test_pairs)} held-out ratings "
      f"from {len(heavy)} users")

# --------------------------- rating matrices ---------------------------------
# NaN = "not rated". Separate lookup dicts keep the prediction code readable.
train_pivot = train_ratings.pivot(index="user_id", columns="movie_id", values="rating")
user_ids = train_pivot.index.to_numpy()
movie_ids = train_pivot.columns.to_numpy()
uid = {u: k for k, u in enumerate(user_ids)}
mid = {m: k for k, m in enumerate(movie_ids)}

R = train_pivot.to_numpy(dtype=float)                      # NaN where unrated
global_mean = np.nanmean(R)
raw_item_means = np.nanmean(R, axis=0)
item_counts = np.sum(~np.isnan(R), axis=0)
user_means = np.nanmean(R, axis=1)

# Bayesian shrinkage: a movie with two 5-star ratings is NOT a "5.0 movie".
# Pull each movie's mean toward the global mean, proportionally to how few
# ratings it has (C=10 pseudo-ratings at the global mean). This kills the
# classic "obscure perfect-score" pathology in both CF and popularity ranking.
SHRINK_C = 10
item_means = (raw_item_means * item_counts + SHRINK_C * global_mean) / (item_counts + SHRINK_C)

# user -> {movie: rating} dict for fast "what did this user rate?" lookups
user_rated = {u: dict(zip(g.movie_id, g.rating)) for u, g in train_ratings.groupby("user_id")}
movie_rated_by = {m: dict(zip(g.user_id, g.rating)) for m, g in train_ratings.groupby("movie_id")}

# --------------------- item-item cosine similarity ----------------------------
# Center each movie's ratings around its own mean (so a 4-star and a 2-star
# movie can still be "similar" if the same users rate them alike), then treat
# missing ratings as 0 (the user expressed no opinion) and take cosine.
R_item = R.copy()
R_item = np.where(np.isnan(R_item), 0, R_item - np.nan_to_num(item_means))
item_sim = cosine_similarity(R_item.T)
np.fill_diagonal(item_sim, 0.0)   # a movie is never its own neighbour

# --------------------- user-user cosine similarity -----------------------------
R_user = R.copy()
R_user = np.where(np.isnan(R_user), 0, R_user - np.nan_to_num(user_means)[:, None])
user_sim = cosine_similarity(R_user)
np.fill_diagonal(user_sim, 0.0)

def predict_item_item(u, m):
    """Weighted average of the user's ratings of similar movies (top-K, sim > 0)."""
    ui, mi = uid[u], mid[m]
    sims = item_sim[mi]
    rated_movies = user_rated.get(u, {})
    neigh = [(sims[mid[mv]], rv - item_means[mid[mv]])
             for mv, rv in rated_movies.items() if sims[mid[mv]] > 0]
    neigh.sort(key=lambda x: -x[0])
    neigh = neigh[:K_ITEM]
    if not neigh:
        return item_means[mi]                      # fallback: the movie's average
    num = sum(s * d for s, d in neigh)
    den = sum(abs(s) for s, _ in neigh)
    return float(np.clip(item_means[mi] + num / den, 1, 5))

def predict_user_user(u, m):
    """Weighted average of similar users' ratings of this movie (top-K)."""
    ui, mi = uid[u], mid[m]
    sims = user_sim[ui]
    rated_users = movie_rated_by.get(m, {})
    neigh = [(sims[uid[v]], rv - user_means[uid[v]])
             for v, rv in rated_users.items() if v in uid and sims[uid[v]] > 0]
    neigh.sort(key=lambda x: -x[0])
    neigh = neigh[:K_USER]
    if not neigh:
        return user_means[ui]                      # fallback: the user's average
    num = sum(s * d for s, d in neigh)
    den = sum(abs(s) for s, _ in neigh)
    return float(np.clip(user_means[ui] + num / den, 1, 5))

def predict_popularity(u, m):
    """Baseline: the movie's (shrunk) average rating, ignoring the user entirely."""
    return item_means[mid[m]]

# Chance baseline: a fixed random score per (user, movie) pair, so ranking is
# a coin flip. Gives context for Precision@5 ("how much better than random?").
_rand = np.random.default_rng(123).random((len(user_ids), len(movie_ids)))
def predict_random(u, m):
    return float(_rand[uid[u], mid[m]])

def recommend(u, n=TOP_N, predict=predict_item_item):
    """Top-n movies the user hasn't rated, scored by `predict`."""
    seen = set(user_rated.get(u, {}))
    cands = [m for m in movie_ids if m not in seen]
    scored = [(m, predict(u, m)) for m in cands]
    scored.sort(key=lambda x: -x[1])
    return scored[:n]

# ------------------------------ evaluation -------------------------------------
methods = {"item-item CF": predict_item_item,
           "user-user CF": predict_user_user,
           "popularity": predict_popularity,
           "random": predict_random}

rmse, mae = {}, {}
for name, fn in methods.items():
    errs = []
    for u, m, true in test_pairs:
        if u in uid and m in mid:
            errs.append(fn(u, m) - true)
    errs = np.array(errs)
    rmse[name] = round(float(np.sqrt((errs ** 2).mean())), 4)
    mae[name] = round(float(np.abs(errs).mean()), 4)
print("\nRMSE:", rmse)
print("MAE: ", mae)

# Precision@K / Recall@K: a held-out rating >= 4 counts as "relevant".
prec5, rec5 = {}, {}
for name, fn in methods.items():
    precisions, recalls = [], []
    for u in heavy:
        relevant = {m for (uu, m, r) in test_pairs if uu == u and r >= 4}
        if not relevant:
            continue
        top5 = {m for m, _ in recommend(u, n=5, predict=fn)}
        hits = len(top5 & relevant)
        precisions.append(hits / 5)
        recalls.append(hits / len(relevant))
    prec5[name] = round(float(np.mean(precisions)), 4)
    rec5[name] = round(float(np.mean(recalls)), 4)
print("P@5:", prec5)
print("R@5:", rec5)

# ----------------------- demo user + explanations ------------------------------
demo_u = max(user_rated, key=lambda u: len(user_rated[u]))
demo_ratings = user_rated[demo_u]
demo_profile = train_ratings[train_ratings.user_id == demo_u].merge(movies, on="movie_id")
fav_genre = (demo_profile.assign(g=lambda d: d.genre_primary)
             .groupby("g")["rating"].agg(["mean", "count"]))
fav_genre = fav_genre[fav_genre["count"] >= 3].sort_values("mean", ascending=False)

def explain(u, m):
    """Why is movie m recommended to user u? Top contributing neighbour movies."""
    ui, mi = uid[u], mid[m]
    sims = item_sim[mi]
    rated = user_rated[u]
    contrib = sorted(
        ((sims[mid[mv]], mv, rv) for mv, rv in rated.items() if sims[mid[mv]] > 0),
        key=lambda x: -x[0] * (x[2] - item_means[mid[x[1]]]))[:2]
    reasons = []
    for s, mv, rv in contrib:
        title = movies.set_index("movie_id").loc[mv, "title"]
        reasons.append(f"you rated '{title}' {rv}/5 (similarity {s:.2f})")
    viewers = movie_rated_by[m]
    avg_viewers = np.mean(list(viewers.values()))
    if not reasons:
        # no positively-similar movies in this user's history: broad-appeal pick
        reasons = [f"broad-appeal pick: {avg_viewers:.1f}/5 average from {len(viewers)} viewers"]
    return reasons, round(float(avg_viewers), 2), len(viewers)

title_of = dict(zip(movies.movie_id, movies.title + " (" + movies.year.astype(str) + ")"))
demo_recs = []
for m, score in recommend(demo_u, n=TOP_N):
    reasons, avg_v, n_v = explain(demo_u, m)
    demo_recs.append({"movie_id": m, "title": title_of[m],
                      "predicted_rating": round(float(score), 2),
                      "similar_viewers_avg": avg_v, "similar_viewers_n": n_v,
                      "because": reasons})
print(f"\nDemo user {demo_u}: {len(demo_ratings)} ratings, avg {np.mean(list(demo_ratings.values())):.2f}")
for r in demo_recs:
    print(f"  -> {r['title']}: predicted {r['predicted_rating']} | because {r['because']}")

# ------------------------------ findings ---------------------------------------
movie_stats = (train_ratings.groupby("movie_id")["rating"]
               .agg(["mean", "count"]).reset_index()
               .merge(movies[["movie_id", "title", "genre_primary"]], on="movie_id"))
top_rated = (movie_stats[movie_stats["count"] >= 10]
             .sort_values("mean", ascending=False).head(5))
hidden_gems = (movie_stats[(movie_stats["count"] >= 5) & (movie_stats["count"] <= 25)]
               .sort_values("mean", ascending=False).head(3))
blockbusters = movie_stats.sort_values("count", ascending=False).head(3)

findings = {
    "dataset": {
        "n_users": int(train_ratings.user_id.nunique()),
        "n_movies": int(len(movies)),
        "n_ratings": int(len(ratings)),
        "density_pct": round(len(ratings) / (300 * 120) * 100, 2),
        "avg_rating": round(float(ratings.rating.mean()), 2),
        "rating_distribution_pct": {str(k): round(v * 100, 1) for k, v in
                                    ratings.rating.value_counts(normalize=True).sort_index().items()},
        "avg_ratings_per_user": round(len(ratings) / ratings.user_id.nunique(), 1),
        "avg_ratings_per_movie": round(len(ratings) / len(movies), 1),
    },
    "methods": {
        "item-item CF": "cosine similarity between mean-centered movie rating vectors; "
                        f"top-{K_ITEM} neighbours, similarity-weighted average",
        "user-user CF": "cosine similarity between mean-centered user rating vectors; "
                        f"top-{K_USER} neighbours",
        "popularity": "baseline: recommend highest average-rated movies, same for everyone",
    },
    "rmse": rmse, "mae": mae,
    "precision_at_5": prec5, "recall_at_5": rec5,
    "n_test_users": int(len(heavy)), "n_test_ratings": int(len(test_pairs)),
    "top_rated_movies": top_rated[["title", "genre_primary", "mean", "count"]]
        .round(2).to_dict("records"),
    "hidden_gems": hidden_gems[["title", "genre_primary", "mean", "count"]]
        .round(2).to_dict("records"),
    "blockbusters": blockbusters[["title", "genre_primary", "mean", "count"]]
        .round(2).to_dict("records"),
    "demo_user": {
        "user_id": demo_u,
        "n_ratings": int(len(demo_ratings)),
        "avg_rating": round(float(np.mean(list(demo_ratings.values()))), 2),
        "top_genres": {g: round(v, 2) for g, v in fav_genre["mean"].head(3).items()},
        "recommendations": demo_recs,
    },
}
with open("findings.json", "w") as f:
    json.dump(findings, f, indent=2)
print("\nfindings.json saved")

# -------------------------------- charts ---------------------------------------
def save(fig, name):
    fig.tight_layout()
    fig.savefig(f"charts/{name}", dpi=130)
    plt.close(fig)
    print(f"charts/{name} saved")

# 1) rating distribution
fig, ax = plt.subplots(figsize=(8, 4.5))
dist = ratings.rating.value_counts(normalize=True).sort_index() * 100
bars = ax.bar(dist.index.astype(str), dist.values, color="#8e44ad", edgecolor="white")
ax.set_title("How users rate movies (1-5 stars)")
ax.set_xlabel("Stars"); ax.set_ylabel("% of all ratings")
for b, v in zip(bars, dist.values):
    ax.text(b.get_x() + b.get_width() / 2, b.get_height() + 0.3, f"{v:.1f}%", ha="center")
ax.text(0.98, 0.95,
        f"{len(ratings):,} ratings\n{findings['dataset']['density_pct']}% of matrix filled\navg {findings['dataset']['avg_rating']} stars",
        transform=ax.transAxes, ha="right", va="top",
        bbox=dict(boxstyle="round", facecolor="white", alpha=0.9))
save(fig, "ratings_distribution.png")

# 2) popularity vs quality: blockbusters vs hidden gems
fig, ax = plt.subplots(figsize=(9, 5))
ms = movie_stats
ax.scatter(ms["count"], ms["mean"], alpha=0.55, s=45, color="#2980b9")
ax.set_title("Popularity vs quality: blockbusters, hidden gems, and everything between")
ax.set_xlabel("Number of ratings (popularity)")
ax.set_ylabel("Average rating (quality)")
for _, row in pd.concat([blockbusters, hidden_gems]).iterrows():
    ax.annotate(row["title"], (row["count"], row["mean"]),
                xytext=(6, 6), textcoords="offset points", fontsize=8)
save(fig, "popularity_vs_quality.png")

# 3) method comparison: RMSE and Precision@5 (random shown only as P@5 context)
fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
names = ["item-item CF", "user-user CF", "popularity"]
colors = ["#27ae60", "#e67e22", "#95a5a6"]
axes[0].bar(names, [rmse[n] for n in names], color=colors)
axes[0].set_title("Rating prediction error (RMSE, lower is better)")
axes[0].set_ylabel("RMSE (stars)")
axes[0].tick_params(axis="x", rotation=12)
for i, n in enumerate(names):
    axes[0].text(i, rmse[n] + 0.01, f"{rmse[n]:.3f}", ha="center")
axes[1].bar(names, [prec5[n] * 100 for n in names], color=colors)
axes[1].set_title("Recommendation quality (Precision@5, higher is better)")
axes[1].set_ylabel("% of top-5 picks the user actually loved")
axes[1].tick_params(axis="x", rotation=12)
for i, n in enumerate(names):
    axes[1].text(i, prec5[n] * 100 + 0.6, f"{prec5[n] * 100:.1f}%", ha="center")
save(fig, "method_comparison.png")

# 4) demo user's top-5, with predicted ratings
fig, ax = plt.subplots(figsize=(9, 4.5))
titles = [r["title"] for r in demo_recs][::-1]
scores = [r["predicted_rating"] for r in demo_recs][::-1]
bars = ax.barh(titles, scores, color="#16a085")
ax.set_title(f"Top-5 recommendations for demo user {demo_u}")
ax.set_xlabel("Predicted rating (stars)")
ax.set_xlim(0, 5.5)
for b, s in zip(bars, scores):
    ax.text(b.get_width() + 0.05, b.get_y() + b.get_height() / 2, f"{s:.2f}", va="center")
save(fig, "demo_recommendations.png")

